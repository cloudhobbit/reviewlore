import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, realpathSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve, dirname } from "node:path";
import { spawnSync } from "node:child_process";
import { detectBaseRef, changedPaths } from "../lib/git-info.mjs";
import { buildIndex, precedentsFor, parseRuleText } from "../lib/review-index.mjs";

const BIN = resolve(import.meta.dirname, "..", "cli", "reviewlore.mjs");
const git = (cwd, ...args) => {
  const r = spawnSync("git", ["-C", cwd, "-c", "user.email=t@t", "-c", "user.name=t", ...args], { encoding: "utf-8" });
  assert.equal(r.status, 0, r.stderr);
  return r.stdout;
};
function write(dir, files) {
  for (const [p, body] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, p)), { recursive: true });
    writeFileSync(join(dir, p), body);
  }
}

// main: a, b, c, old-name; feature: a modified, b deleted, old-name renamed,
// d added; then c modified (unstaged) and e untracked.
function repo() {
  const dir = realpathSync(mkdtempSync(join(tmpdir(), "precedents-")));
  git(dir, "init", "-q", "-b", "main");
  git(dir, "remote", "add", "origin", "https://github.com/o/r.git");
  write(dir, { "src/a.ts": "a\n", "src/b.ts": "b\n", "src/c.ts": "c\n", "src/old-name.ts": "x\n".repeat(20) });
  git(dir, "add", "-A");
  git(dir, "commit", "-qm", "init");
  git(dir, "checkout", "-qb", "feature");
  write(dir, { "src/a.ts": "a2\n", "src/d.ts": "d\n" });
  git(dir, "rm", "-q", "src/b.ts");
  git(dir, "mv", "src/old-name.ts", "src/new-name.ts");
  git(dir, "add", "-A");
  git(dir, "commit", "-qm", "feature");
  write(dir, { "src/c.ts": "c2\n", "src/e.ts": "e\n" });
  return dir;
}

test("detectBaseRef: explicit, then origin/HEAD, then the usual names; local refs only", () => {
  const dir = repo();
  try {
    assert.equal(detectBaseRef(dir), "main", "no origin refs: falls back to main");
    assert.equal(detectBaseRef(dir, "feature"), "feature");
    assert.equal(detectBaseRef(dir, "nope"), null);
    git(dir, "update-ref", "refs/remotes/origin/trunk", "main");
    git(dir, "symbolic-ref", "refs/remotes/origin/HEAD", "refs/remotes/origin/trunk");
    assert.equal(detectBaseRef(dir), "origin/trunk");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("changedPaths: committed, unstaged and untracked changes with statuses", () => {
  const dir = repo();
  try {
    const { mergeBase, changed } = changedPaths(dir, "main");
    assert.match(mergeBase, /^[0-9a-f]{40}$/);
    assert.deepEqual(changed, [
      { path: "src/a.ts", status: "M" },
      { path: "src/b.ts", status: "D" },
      { path: "src/c.ts", status: "M" },
      { path: "src/d.ts", status: "A" },
      { path: "src/e.ts", status: "U" },
      { path: "src/new-name.ts", status: "R" },
    ]);
    assert.equal(changedPaths(dir, "nope"), null);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

const RULE = (paths, title) => `${paths ? `---\npaths:\n${paths.map((p) => `  - "${p}"`).join("\n")}\n---\n` : ""}<!-- Generated by reviewlore (learn-from-reviews) from PR review history. -->\n\n# ${title}\n\nDo it.\n\n## Examples from PR review history\n\n- > q\n  — @a on PR #1: https://github.com/o/r/pull/1#issuecomment-1\n`;
const ic = (i, author, pr, body, extra = {}) => ({ type: "issue_comment", comment_id: i, pr_number: pr, author, author_type: "User", body, created_at: "2026-09-01T00:00:00Z", html_url: `https://github.com/o/r/pull/${pr}#issuecomment-${i}`, ...extra });
const rc = (i, author, pr, path, body) => ({ type: "review_comment", comment_id: i, pr_number: pr, author, author_type: "User", body, path, line: 1, in_reply_to_id: null, created_at: "2026-09-01T00:00:00Z", html_url: `https://github.com/o/r/pull/${pr}#discussion_r${i}` });

function data() {
  return {
    meta: { owner: "o", repo: "r", fetched_at: "2026-09-20T00:00:00Z", pr_authors: {} },
    issue_comments: [
      ic(1, "alice", 1, "Please add a changeset for this change."),
      ic(2, "bob", 2, "Please add a changeset for this change too."),
    ],
    review_comments: [
      rc(10, "carol", 3, "src/api/users.ts", "Please add a unit test for the empty input case."),
      rc(11, "dave", 4, "src/api/posts.ts", "Please add a unit test for the empty input here."),
      rc(12, "erin", 5, "docs/guide.md", "Please fix the typo in this heading."),
    ],
    review_submissions: [],
  };
}

test("precedentsFor: scoped rules by glob, unscoped rules, recurring by area, file history", () => {
  const rules = [
    parseRuleText(RULE(["src/api/**/*.ts"], "API rule"), ".claude/rules/pr-feedback-api.md"),
    parseRuleText(RULE(["docs/**/*.md"], "Docs rule"), ".claude/rules/pr-feedback-docs.md"),
    parseRuleText(RULE(null, "Add a changeset"), ".claude/rules/pr-feedback-changeset.md"),
  ];
  const index = buildIndex(data(), { rules, clusters: true });
  const p = precedentsFor(index, [{ path: "src/api/users.ts", status: "M" }, { path: "src/old.ts", status: "D" }], { now: Date.parse("2026-09-30T00:00:00Z") });
  assert.deepEqual(p.rules.map((r) => [r.title, r.unscoped, r.matched]), [
    ["API rule", false, ["src/api/users.ts"]],
    ["Add a changeset", true, []],
  ]);
  assert.ok(p.recurring.some((r) => r.scope === "src/**/*.ts" && r.prs === 2 && r.reviewers === 2), JSON.stringify(p.recurring));
  assert.ok(p.recurring.some((r) => r.scope === null), "PR-wide changeset feedback");
  assert.equal(p.file_history.length, 1);
  assert.equal(p.file_history[0].same_file, 1);
  assert.equal(p.file_history[0].comments[0].match, "file");
  assert.deepEqual(p.stats, { changed: 2, rules_matched: 1, rules_unscoped: 1, recurring: p.recurring.length, files_with_history: 1 });
});

function precedents(cwd, args = [], env = {}) {
  const r = spawnSync(process.execPath, [BIN, "precedents", ...args], { cwd, encoding: "utf-8", env: { PATH: process.env.PATH, GITHUB_TOKEN: "", ...env } });
  return { ...r, json: r.stdout ? JSON.parse(r.stdout) : null };
}

test("reviewlore precedents: statuses, no-data still checks rules, deterministic output", () => {
  const dir = repo();
  const cache = mkdtempSync(join(tmpdir(), "precedents-cache-"));
  const outside = mkdtempSync(join(tmpdir(), "precedents-out-"));
  try {
    const env = { REVIEWLORE_CACHE_DIR: cache };
    assert.equal(precedents(outside, [], env).json.status, "not-a-repo");
    const noBase = precedents(dir, ["--base", "nope"], env);
    assert.equal(noBase.status, 0);
    assert.equal(noBase.json.status, "no-base");

    write(dir, { ".claude/rules/pr-feedback-src.md": RULE(["src/**/*.ts"], "Src rule") });
    const noData = precedents(dir, [], env).json;
    assert.equal(noData.status, "no-data");
    assert.match(noData.hint, /No review history for o\/r/);
    assert.deepEqual(noData.rules.map((r) => r.title), ["Src rule"]);

    writeFileSync(join(cache, "o__r.json"), JSON.stringify(data()));
    const a = precedents(dir, ["--paths", "src/api/users.ts,./src/a.ts"], env);
    const b = precedents(dir, ["--paths", "src/api/users.ts,./src/a.ts"], env);
    assert.equal(a.status, 0, a.stderr);
    assert.equal(a.stdout, b.stdout, "byte-identical");
    assert.equal(a.json.status, "ok");
    assert.equal(a.json.data.source, "cache");
    assert.deepEqual(a.json.changed.map((c) => c.path), ["src/a.ts", "src/api/users.ts"]);
    assert.equal(a.stderr, "");

    assert.equal(precedents(dir, ["--limit", "0"], env).status, 1);
  } finally {
    for (const d of [dir, cache, outside]) rmSync(d, { recursive: true, force: true });
  }
});
