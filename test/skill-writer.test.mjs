import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, writeFileSync, rmSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { renderRule, writeSkills, renderSummary, yamlQuote } from "../lib/skill-writer.mjs";

const sampleCluster = {
  label: ["test", "missing", "edge"],
  occurrences: 4,
  distinctAuthors: 3,
  distinctPRs: 4,
  authors: ["alice", "bob", "carol"],
  paths: ["src/a.ts", "src/b.tsx"],
  kinds: ["request", "prescription"],
  items: [
    { sentence: "Please add a test for the empty-array case.", author: "alice", pr: 1, url: "u1" },
    { sentence: "Missing test for the null-input case.", author: "bob", pr: 2, url: "u2" },
    { sentence: "We should add tests for edge cases here.", author: "carol", pr: 3, url: "u3" },
    { sentence: "Add a test for the boundary.", author: "alice", pr: 4, url: "u4" },
  ],
};

test("renderRule scopes the rule with Claude Code `paths:` frontmatter + body sections", () => {
  const { slug, body } = renderRule(sampleCluster);
  assert.match(slug, /test/);
  assert.match(body, /^---\npaths:\n  - "src\/\*\*\/\*\.ts"\n  - "src\/\*\*\/\*\.tsx"\n---\n/);
  // Claude Code ignores every other frontmatter field, so none are emitted.
  assert.doesNotMatch(body, /^(name|description|type):/m);
  assert.match(body, /^# .*test/m);
  assert.match(body, /\*\*Why:\*\*/);
  assert.match(body, /\*\*How to apply:\*\*/);
  assert.match(body, /\.ts/);
  assert.match(body, /@alice/);
});

test("writeSkills creates .claude/rules/ files in target", () => {
  const target = mkdtempSync(join(tmpdir(), "pr-skills-"));
  try {
    const { written, skipped } = writeSkills([sampleCluster], { targetDir: target });
    assert.equal(written.length, 1);
    assert.equal(skipped.length, 0);
    const files = readdirSync(join(target, ".claude", "rules"));
    assert.equal(files.length, 1);
    assert.match(files[0], /^pr-feedback-/);
    const content = readFileSync(join(target, ".claude", "rules", files[0]), "utf-8");
    assert.match(content, /Reviewer feedback recurring/);
  } finally {
    rmSync(target, { recursive: true, force: true });
  }
});

test("writeSkills skips existing files unless force=true (regression: #6)", () => {
  const target = mkdtempSync(join(tmpdir(), "pr-skills-"));
  try {
    const first = writeSkills([sampleCluster], { targetDir: target });
    assert.equal(first.written.length, 1);
    const filePath = first.written[0].path;
    // User "edits" the file
    const userEdit = "USER EDIT — do not clobber";
    writeFileSync(filePath, userEdit, "utf-8");

    // Second run without force: should skip
    const second = writeSkills([sampleCluster], { targetDir: target });
    assert.equal(second.written.length, 0);
    assert.equal(second.skipped.length, 1);
    assert.equal(readFileSync(filePath, "utf-8"), userEdit, "file should be untouched");

    // Second run with force: should overwrite
    const third = writeSkills([sampleCluster], { targetDir: target, force: true });
    assert.equal(third.written.length, 1);
    assert.notEqual(readFileSync(filePath, "utf-8"), userEdit);
  } finally {
    rmSync(target, { recursive: true, force: true });
  }
});

test("yamlQuote escapes backslashes, quotes, and collapses whitespace (regression: #4)", () => {
  assert.equal(yamlQuote("plain"), '"plain"');
  assert.equal(yamlQuote('has "quote"'), '"has \\"quote\\""');
  assert.equal(yamlQuote("multi\nline\ttext"), '"multi line text"');
  assert.equal(yamlQuote("path with \\ backslash"), '"path with \\\\ backslash"');
});

test("renderRule frontmatter stays valid YAML: only quoted globs, never sentence text (regression: #4)", () => {
  const cluster = {
    ...sampleCluster,
    paths: ["src/odd: name.ts"],
    items: [
      { sentence: "Use X: not Y.", author: "a", pr: 1, url: "u" },
      { sentence: "Avoid Z: prefer W.", author: "b", pr: 2, url: "u" },
      { sentence: "Third example: short.", author: "c", pr: 3, url: "u" },
    ],
  };
  const { body } = renderRule(cluster);
  const fm = body.split("---\n")[1];
  assert.equal(fm, 'paths:\n  - "src/**/*.ts"\n');
});

test("renderRule without file paths emits no frontmatter (rule applies everywhere)", () => {
  const { body } = renderRule({ ...sampleCluster, paths: [] });
  assert.match(body, /^<!-- Generated by reviewlore/);
});

test("renderSummary lists each cluster", () => {
  const out = renderSummary([sampleCluster], {
    owner: "o", repo: "r", months_back: 6, since: "2025-01-01",
  });
  assert.match(out, /Clusters extracted: 1/);
  assert.match(out, /4× across 3 authors/);
});

test("writeSkills never overwrites a plugin-written rule, even with force", () => {
  const target = mkdtempSync(join(tmpdir(), "pr-skills-"));
  try {
    const { written } = writeSkills([sampleCluster], { targetDir: target });
    const path = written[0].path;
    const pluginRule = "<!-- Generated by reviewlore (learn-from-reviews) from PR review history. -->\n# Mine\n";
    writeFileSync(path, pluginRule);
    const again = writeSkills([sampleCluster], { targetDir: target, force: true });
    assert.equal(again.written.length, 0);
    assert.equal(again.skipped.length, 1);
    assert.equal(readFileSync(path, "utf-8"), pluginRule);
  } finally {
    rmSync(target, { recursive: true, force: true });
  }
});
