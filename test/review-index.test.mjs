import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, utimesSync, realpathSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";
import { buildIndex, searchIndex, feedbackForPath, parseRuleText, clip } from "../lib/review-index.mjs";
import { globCoversPath } from "../lib/globs.mjs";

const t = (d) => `2026-09-${String(d).padStart(2, "0")}T10:00:00Z`;
let n = 0;
const rc = (author, pr, path, body, day, extra = {}) => ({
  type: "review_comment", comment_id: ++n, pr_number: pr, author, author_type: "User", body, path, line: 1,
  in_reply_to_id: null, created_at: t(day), html_url: `https://github.com/o/r/pull/${pr}#discussion_r${n}`, ...extra,
});
const ic = (author, pr, body, day) => ({
  type: "issue_comment", comment_id: ++n, pr_number: pr, author, author_type: "User", body,
  created_at: t(day), html_url: `https://github.com/o/r/pull/${pr}#issuecomment-${n}`,
});

function corpus() {
  n = 0;
  const root = rc("alice", 1, "src/api/users.ts", "Please validate the request body before using it.", 1);
  const resolved = rc("bob", 2, "src/api/posts.ts", "Avoid mutating the shared config object here.", 2);
  return {
    meta: { owner: "o", repo: "r", fetched_at: t(28), pr_authors: { 1: "author1", 2: "author2", 3: "author3", 4: "author4", 5: "author5" } },
    issue_comments: [
      ic("carol", 3, "Please add a changeset for this change.", 3),
      ic("dave", 4, "This needs a changeset since it changes the CLI.", 4),
      ic("erin", 5, "Thanks!", 5),
    ],
    review_comments: [
      root,
      rc("carol", 1, "src/api/users.ts", "Agreed, and please return a 400 when it's invalid.", 2, { in_reply_to_id: root.comment_id }),
      resolved,
      rc("author2", 2, "src/api/posts.ts", "Done", 3, { in_reply_to_id: resolved.comment_id }),
      rc("dave", 3, "src/api/users.ts", "Can we use the shared validator helper here?", 6),
      rc("erin", 4, "src/web/page.tsx", "Prefer the design-system Button over a raw button.", 7),
      rc("frank", 5, "src/api/util/strings.ts", "Please add a unit test for the empty string.", 8),
      rc("frank", 4, "src/api/util/strings.ts", "Please add a unit test for the empty string case.", 9),
      rc("dependabot[bot]", 5, "src/api/users.ts", "Bumps the version of a dependency used here.", 9, { author_type: "Bot" }),
    ],
    review_submissions: [],
  };
}

const RULE = `---
paths:
  - "src/api/**/*.ts"
---
<!-- Generated by reviewlore (learn-from-reviews) from PR review history. Review, edit or delete freely. -->

# Add a changeset for every user-facing change

Include a changeset in \`.changeset/\` for every change users can see.

**Why:** Requested on 2 PRs by 2 reviewers.

## Examples from PR review history

- > Please add a changeset for this change.
  — @carol on PR #3: https://github.com/o/r/pull/3#issuecomment-3
`;

test("parseRuleText reads paths, title, body, links and provenance", () => {
  const r = parseRuleText(RULE, ".claude/rules/pr-feedback-add-a-changeset.md");
  assert.deepEqual(r.paths, ["src/api/**/*.ts"]);
  assert.equal(r.title, "Add a changeset for every user-facing change");
  assert.match(r.body, /Include a changeset/);
  assert.deepEqual(r.urls, ["https://github.com/o/r/pull/3#issuecomment-3"]);
  assert.equal(r.generated, true);
  const hand = parseRuleText("---\npaths: [\"docs/**\", 'site/**']\n---\n# Docs tone\nWrite in second person.\n", "x.md");
  assert.deepEqual(hand.paths, ["docs/**", "site/**"]);
  assert.equal(hand.generated, false);
});

test("searchIndex: rules first, then comments by BM25, with honest support", () => {
  const idx = buildIndex(corpus(), { rules: [parseRuleText(RULE, "pr-feedback-add-a-changeset.md")] });
  const r = searchIndex(idx, "add a changeset", { limit: 5 });
  assert.equal(r.rules[0].title, "Add a changeset for every user-facing change");
  // Both changeset comments rank above everything else for "changeset".
  assert.deepEqual(searchIndex(idx, "changeset").results.slice(0, 2).map((x) => x.author).sort(), ["carol", "dave"]);
  assert.ok(r.results.every((x) => x.source === "review"));
  assert.equal(r.support.reviewers, new Set(r.results.map((x) => x.author)).size);
  // Prefix expansion: "validation" finds "validate" / "validator".
  assert.ok(searchIndex(idx, "validation").results.some((x) => /validat/.test(x.quote)));
  // Deterministic.
  assert.equal(JSON.stringify(searchIndex(idx, "changeset")), JSON.stringify(searchIndex(idx, "changeset")));
  // No bot, no praise, no PR author.
  const all = searchIndex(idx, "thanks dependency version done", { limit: 50 }).results;
  assert.ok(!all.some((x) => ["dependabot[bot]", "author2"].includes(x.author) || /^Thanks/.test(x.quote)));
});

test("feedbackForPath: same file first, threads collapsed, resolved threads gone, near-duplicates merged", () => {
  const idx = buildIndex(corpus(), { rules: [parseRuleText(RULE, "pr-feedback-add-a-changeset.md")] });
  const f = feedbackForPath(idx, "src/api/users.ts", { now: Date.parse(t(28)) });
  assert.equal(f.rules.length, 1, "the rule scoped to src/api/**/*.ts");
  assert.deepEqual(f.comments.slice(0, 2).map((c) => c.author), ["alice", "dave"], "same file: thread root (request) then question");
  assert.equal(f.comments[0].replies, 1);
  assert.ok(!f.comments.some((c) => /mutating the shared config/.test(c.quote)), "resolved by the PR author");
  const strings = f.comments.filter((c) => c.path === "src/api/util/strings.ts");
  assert.equal(strings.length, 1);
  assert.equal(strings[0].similar, 1);
  assert.ok(!f.comments.some((c) => c.path.startsWith("src/web")), "outside the package scope");
  // A directory, and a months cutoff.
  assert.ok(feedbackForPath(idx, "src/api", { now: Date.parse(t(28)) }).comments.length >= 3);
  assert.equal(feedbackForPath(idx, "src/api", { months: 0, now: Date.parse(t(28)) }).comments.length, 0);
});

test("clip and globCoversPath", () => {
  assert.equal(clip("**Bold** text"), "Bold text");
  assert.equal(clip("x".repeat(500)).length, 400);
  assert.ok(globCoversPath("src/api/**/*.ts", "src/api/users.ts"));
  assert.ok(globCoversPath("src/api/**/*.ts", "src/api"), "a directory the glob reaches into");
  assert.ok(globCoversPath("src/api/**/*.ts", "src"), "a parent directory");
  assert.ok(!globCoversPath("src/api/**/*.ts", "src/web"));
  assert.ok(!globCoversPath("src/api/**/*.ts", "src/api/readme.md"));
});

// The MCP tools inside a repo: no owner/repo, corpus vs cache, memo.
test("MCP tools: zero-argument use inside a repo, newer source wins, index rebuilt on change", async () => {
  const tools = await import("../lib/mcp-tools.mjs");
  const repo = realpathSync(mkdtempSync(join(tmpdir(), "mcp-repo-")));
  const cache = mkdtempSync(join(tmpdir(), "mcp-cache-"));
  const env = { project: process.env.REVIEWLORE_PROJECT_DIR, cache: process.env.REVIEWLORE_CACHE_DIR };
  try {
    spawnSync("git", ["init", "-q", repo]);
    spawnSync("git", ["-C", repo, "remote", "add", "origin", "git@github.com:o/r.git"]);
    mkdirSync(join(repo, ".claude", "rules"), { recursive: true });
    mkdirSync(join(repo, "packages", "x"), { recursive: true });
    writeFileSync(join(repo, ".claude/rules/pr-feedback-add-a-changeset.md"), RULE);
    writeFileSync(join(repo, ".reviewlore-corpus.json"), JSON.stringify(corpus()));
    process.env.REVIEWLORE_PROJECT_DIR = join(repo, "packages", "x"); // a subdirectory
    process.env.REVIEWLORE_CACHE_DIR = cache;
    tools.clearMemo();

    const f = await tools.reviewFeedbackForPath({ path: "src/api/users.ts" });
    assert.equal(f.repo, "o/r");
    assert.equal(f.source, "corpus");
    assert.equal(f.rules[0].title, "Add a changeset for every user-facing change");
    assert.ok(f.comments.length > 0);
    const s = await tools.searchReviewFeedback({ query: "changeset" });
    assert.ok(s.rules.length === 1 && s.results.length >= 2);
    assert.equal(tools.listRepos().find((r) => r.default)?.repo, "r");

    // A newer personal cache wins; an older one doesn't.
    const newer = corpus();
    newer.meta.fetched_at = "2026-10-01T00:00:00Z";
    newer.issue_comments.push({ ...newer.issue_comments[0], comment_id: 999, author: "gina", body: "Please add a changeset entry, release notes come from it.", html_url: "https://github.com/o/r/pull/9#issuecomment-999", pr_number: 9 });
    writeFileSync(join(cache, "o__r.json"), JSON.stringify(newer, null, 2));
    const fromCache = await tools.searchReviewFeedback({ query: "changeset release notes" });
    assert.equal(fromCache.source, "cache");
    assert.equal(fromCache.results[0].author, "gina");

    // Editing the rule file rebuilds the index.
    writeFileSync(join(repo, ".claude/rules/pr-feedback-add-a-changeset.md"), RULE.replace("Add a changeset", "Always add a changeset"));
    const later = new Date(Date.now() + 5000);
    utimesSync(join(repo, ".claude/rules/pr-feedback-add-a-changeset.md"), later, later);
    assert.match((await tools.searchReviewFeedback({ query: "changeset" })).rules[0].title, /^Always add/);

    // Outside any repo, a clear hint.
    process.env.REVIEWLORE_PROJECT_DIR = cache;
    assert.match((await tools.reviewFeedbackForPath({ path: "src" })).hint, /Couldn't tell which GitHub repository/);
  } finally {
    for (const [k, v] of [["REVIEWLORE_PROJECT_DIR", env.project], ["REVIEWLORE_CACHE_DIR", env.cache]]) {
      if (v === undefined) delete process.env[k];
      else process.env[k] = v;
    }
    rmSync(repo, { recursive: true, force: true });
    rmSync(cache, { recursive: true, force: true });
  }
});

test("MCP responses stay under the size guard", async () => {
  const { fit } = await import("../lib/mcp-tools.mjs");
  const big = { comments: Array.from({ length: 100 }, (_, i) => ({ quote: "x".repeat(400), i })) };
  const out = fit(big, "comments");
  assert.ok(JSON.stringify(out).length <= 16_000);
  assert.equal(out.comments.length + out.more, 100);
});

test("an index built in a child process equals one built in-process", async () => {
  const { buildInChild } = await import("../lib/mcp-tools.mjs");
  const dir = mkdtempSync(join(tmpdir(), "child-build-"));
  try {
    const data = corpus();
    writeFileSync(join(dir, "data.json"), JSON.stringify(data));
    const rules = [parseRuleText(RULE, "pr-feedback-add-a-changeset.md")];
    const child = await buildInChild(join(dir, "data.json"), rules);
    const local = buildIndex(data, { rules, clusters: true });
    assert.ok(child.sentenceIndex.postings instanceof Map && child.comments[0].tokens instanceof Set);
    assert.deepEqual(searchIndex(child, "changeset"), searchIndex(local, "changeset"));
    assert.deepEqual(feedbackForPath(child, "src/api", { now: Date.parse(t(28)) }), feedbackForPath(local, "src/api", { now: Date.parse(t(28)) }));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("replies in threads a bot started are not review feedback", () => {
  const data = corpus();
  const bot = rc("coderabbitai[bot]", 4, "src/api/users.ts", "Consider extracting this into a helper function for reuse.", 10, { author_type: "Bot" });
  data.review_comments.push(bot,
    rc("dave", 4, "src/api/users.ts", "Declined: the helper would only have one caller here.", 11, { in_reply_to_id: bot.comment_id }));
  const f = feedbackForPath(buildIndex(data), "src/api/users.ts", { now: Date.parse(t(28)) });
  assert.ok(!f.comments.some((c) => /Declined/.test(c.quote)));
  assert.ok(f.comments.some((c) => c.author === "alice"), "human-started threads stay");
});
