const BIN = resolve(import.meta.dirname, "..", "cli", "reviewlore.mjs");
const NOW = Date.parse("2026-10-27T00:00:00Z");
const PROV = "<!-- Generated by reviewlore (learn-from-reviews) from PR review history. Review, edit or delete freely. -->";
const rule = (title, paths, cites) => `${paths ? `---\npaths:\n${paths.map((p) => `  - "${p}"`).join("\n")}\n---\n` : ""}${PROV}\n\n# ${title}\n\nDo it.\n\n## Examples from PR review history\n\n${cites.map(([q, a, pr, id]) => `- > ${q}\n  — @${a} on PR #${pr}: https://github.com/o/r/pull/${pr}#issuecomment-${id}`).join("\n")}\n`;
const ic = (id, author, pr, body, at) => ({ type: "issue_comment", comment_id: id, pr_number: pr, author, author_type: "User", body, created_at: at, html_url: `https://github.com/o/r/pull/${pr}#issuecomment-${id}` });

function repo(files) {
  const dir = realpathSync(mkdtempSync(join(tmpdir(), "rules-")));
  spawnSync("git", ["init", "-q", dir]);
  spawnSync("git", ["-C", dir, "remote", "add", "origin", "https://github.com/o/r.git"]);
  for (const [p, body] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, p)), { recursive: true });
    writeFileSync(join(dir, p), body);
  }
  spawnSync("git", ["-C", dir, "add", "-A"]);
  return dir;
}

// Old citations (2026-01) plus fresh support (2026-09) for the changeset rule;
// a fresh "no need for a changeset" from two reviewers for the docs rule.
const DATA = {
  meta: { owner: "o", repo: "r", fetched_at: "2026-10-20T00:00:00Z", pr_authors: {} },
  issue_comments: [
    ic(1, "alice", 1, "Please add a changeset for this.", "2026-01-10T00:00:00Z"),
    ic(2, "bob", 2, "This needs a changeset too.", "2026-01-12T00:00:00Z"),
    ic(3, "carol", 3, "Please add a changeset here as well.", "2026-09-01T00:00:00Z"),
    ic(4, "dave", 4, "Please add a changeset before merging.", "2026-09-05T00:00:00Z"),
    ic(5, "erin", 5, "Please document the new flag in the guide.", "2026-01-15T00:00:00Z"),
    ic(6, "frank", 6, "Please document the option in the guide.", "2026-01-20T00:00:00Z"),
    ic(7, "carol", 7, "No need to document the flag in the guide.", "2026-09-10T00:00:00Z"),
    ic(8, "dave", 8, "No need to document this flag in the guide.", "2026-09-12T00:00:00Z"),
  ],
  review_comments: [],
  review_submissions: [],
};
const urlMap = (data) => new Map(data.issue_comments.map((c) => [c.html_url, c]));

test("manifest: entries from rule files, sorted, written only when changed", () => {
  const dir = repo({ ".claude/rules/pr-feedback-add-a-changeset.md": rule("Add a changeset", null, [["Please add a changeset for this.", "alice", 1, 1], ["This needs a changeset too.", "bob", 2, 2]]) });
  try {
    const now = new Date(NOW);
    const r = recordFiles(dir, ["pr-feedback-add-a-changeset.md", "pr-feedback-nope.md"], { byUrl: urlMap(DATA), ctx: { owner: "o", repo: "r", source: "cache", fetchedAt: "2026-10-20T00:00:00Z" }, now });
    assert.deepEqual(r, { recorded: ["pr-feedback-add-a-changeset.md"], skipped: ["pr-feedback-nope.md"] });
    const m = loadManifest(dir);
    const e = m.rules["pr-feedback-add-a-changeset.md"];
    assert.equal(m.repo, "o/r");
    assert.equal(e.generator, "learn-from-reviews");
    assert.deepEqual(e.support, { prs: 2, reviewers: 2 });
    assert.deepEqual(e.evidence.map((x) => x.at), ["2026-01-10", "2026-01-12"]);
    assert.equal(e.sha256, fileSha(readFileSync(join(dir, ".claude/rules/pr-feedback-add-a-changeset.md"), "utf-8")));
    const text = readFileSync(manifestPath(dir), "utf-8");
    assert.ok(text.indexOf('"dismissed"') < text.indexOf('"repo"'), "keys sorted");
    const mtime = statSync(manifestPath(dir)).mtimeMs;
    assert.equal(saveManifest(dir, loadManifest(dir)), false, "no write when equal");
    assert.equal(statSync(manifestPath(dir)).mtimeMs, mtime);
    // Re-recording keeps `created`.
    recordFiles(dir, ["pr-feedback-add-a-changeset.md"], { byUrl: urlMap(DATA), now: new Date(NOW + 86_400_000) });
    assert.equal(loadManifest(dir).rules["pr-feedback-add-a-changeset.md"].created, "2026-10-27");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("status: refresh old quotes, paths gone, deleted, edited, unmanaged, contradictions only with a query", () => {
  const dir = repo({
    "src/a.ts": "x",
    ".claude/rules/pr-feedback-add-a-changeset.md": rule("Add a changeset", ["src/**/*.ts"], [["Please add a changeset for this.", "alice", 1, 1], ["This needs a changeset too.", "bob", 2, 2]]),
    ".claude/rules/pr-feedback-document-flags.md": rule("Document new flags", null, [["Please document the new flag in the guide.", "erin", 5, 5], ["Please document the option in the guide.", "frank", 6, 6]]),
    ".claude/rules/pr-feedback-docs-only.md": rule("Docs rule", ["docs/**/*.md"], [["Please add a changeset for this.", "alice", 1, 1], ["This needs a changeset too.", "bob", 2, 2]]),
    ".claude/rules/pr-feedback-gone.md": rule("Gone rule", null, [["Please add a changeset for this.", "alice", 1, 1], ["This needs a changeset too.", "bob", 2, 2]]),
    ".claude/rules/pr-feedback-legacy.md": rule("Legacy", null, [["Please add a changeset for this.", "alice", 1, 1], ["This needs a changeset too.", "bob", 2, 2]]),
  });
  try {
    const names = ["pr-feedback-add-a-changeset.md", "pr-feedback-document-flags.md", "pr-feedback-docs-only.md", "pr-feedback-gone.md"];
    recordFiles(dir, names, { byUrl: urlMap(DATA), now: new Date(NOW) });
    recordFiles(dir, ["pr-feedback-document-flags.md"], { byUrl: urlMap(DATA), query: "document flag guide", now: new Date(NOW) });
    unlinkSync(join(dir, ".claude/rules/pr-feedback-gone.md"));
    writeFileSync(join(dir, ".claude/rules/pr-feedback-docs-only.md"), readFileSync(join(dir, ".claude/rules/pr-feedback-docs-only.md"), "utf-8") + "\nEdited.\n");
    const status = ruleStatus({ targetDir: dir, manifest: loadManifest(dir), index: buildIndex(DATA), tracked: ["src/a.ts"], months: 6, now: NOW });
    const by = Object.fromEntries(status.rules.map((r) => [r.file, r]));
    const changeset = by["pr-feedback-add-a-changeset.md"];
    assert.equal(changeset.suggest, "update", "old quotes, fresh support: refresh, don't retire");
    assert.ok(changeset.flags.includes("evidence-aged-out"));
    assert.deepEqual([changeset.recent_support.prs, changeset.recent_support.reviewers], [2, 2]);
    assert.equal(by["pr-feedback-docs-only.md"].suggest, "review-retire");
    assert.ok(by["pr-feedback-docs-only.md"].flags.includes("paths-gone") && by["pr-feedback-docs-only.md"].flags.includes("edited"));
    assert.equal(by["pr-feedback-gone.md"].suggest, "dismiss");
    assert.equal(by["pr-feedback-document-flags.md"].suggest, "check");
    assert.equal(by["pr-feedback-document-flags.md"].contradictions.length, 2);
    assert.deepEqual(status.unmanaged, ["pr-feedback-legacy.md"]);
    const md = renderStatus(status, { repo: "o/r", source: "cache", ageDays: 7, months: 6 });
    assert.match(md, /\| Add a changeset \(`pr-feedback-add-a-changeset\.md`\) \| update: refresh quotes \| 2 PRs \/ 2 reviewers/);
    assert.match(md, /Possible contradictions for pr-feedback-document-flags\.md/);
    assert.match(md, /Not tracked yet .*pr-feedback-legacy\.md/);
    // Without a recorded query, no contradiction guesses.
    const m = loadManifest(dir);
    delete m.rules["pr-feedback-document-flags.md"].query;
    const plain = ruleStatus({ targetDir: dir, manifest: m, index: buildIndex(DATA), tracked: ["src/a.ts"], months: 6, now: NOW });
    assert.ok(!plain.rules.find((r) => r.file === "pr-feedback-document-flags.md").flags.includes("contradiction-candidates"));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("status: older matches outside the window don't crowd out recent support", () => {
  const dir = mkdtempSync(join(tmpdir(), "rules-crowd-"));
  try {
    const comment = (i, date, body) => ({ type: "review_comment", comment_id: i, pr_number: i, author: `rv${i % 9}`, author_type: "User", body, path: "src/a.ts", line: 1, created_at: date, html_url: `https://github.com/o/r/pull/${i}#discussion_r${i}` });
    // 60 short, high-scoring matches from long ago; 3 longer recent ones.
    const old = Array.from({ length: 60 }, (_, i) => comment(i + 1, "2025-01-10T00:00:00Z", "Please add a changeset here."));
    const recent = [100, 101, 102].map((i) => comment(i, "2026-10-01T00:00:00Z", `Please add a changeset for this package change, the release tooling in this monorepo needs one for every published package ${i}.`));
    const index = buildIndex({ meta: { pr_authors: {} }, issue_comments: [], review_comments: [...old, ...recent], review_submissions: [] });
    const file = "pr-feedback-add-a-changeset.md";
    mkdirSync(join(dir, ".claude/rules"), { recursive: true });
    writeFileSync(join(dir, ".claude/rules", file), "<!-- Generated by reviewlore -->\n\n# Add a changeset\n\nAdd one.\n");
    const manifest = { version: 1, rules: { [file]: { title: "Add a changeset", sha256: "x", evidence: [], generator: "learn-from-reviews", query: "changeset" } }, dismissed: [] };
    const [r] = ruleStatus({ targetDir: dir, manifest, index, tracked: ["src/a.ts"], months: 6, now: Date.parse("2026-10-28T00:00:00Z") }).rules;
    assert.equal(r.recent_support.prs, 3);
    assert.ok(!r.flags.includes("no-recent-support"));
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("reviewlore rules: record --all, status exits 0, dismiss and retire need the file gone", () => {
  const dir = repo({ ".claude/rules/pr-feedback-add-a-changeset.md": rule("Add a changeset", null, [["Please add a changeset for this.", "alice", 1, 1], ["This needs a changeset too.", "bob", 2, 2]]) });
  const cache = mkdtempSync(join(tmpdir(), "rules-cache-"));
  try {
    writeFileSync(join(cache, "o__r.json"), JSON.stringify(DATA));
    const run = (...args) => spawnSync(process.execPath, [BIN, "rules", ...args, "--target", dir], { encoding: "utf-8", env: { PATH: process.env.PATH, REVIEWLORE_CACHE_DIR: cache, GITHUB_TOKEN: "" } });
    assert.equal(run("record", "--all").status, 0);
    assert.ok(loadManifest(dir).rules["pr-feedback-add-a-changeset.md"]);
    const st = run("status");
    assert.equal(st.status, 0, st.stderr);
    assert.match(st.stdout, /# Review rules status — o\/r/);
    assert.equal(JSON.parse(run("status", "--json").stdout).stats.rules, 1);
    assert.equal(run("retire", "pr-feedback-add-a-changeset.md").status, 1, "file still exists");
    assert.equal(run("dismiss", "pr-feedback-add-a-changeset.md").status, 1, "file still exists");
    unlinkSync(join(dir, ".claude/rules/pr-feedback-add-a-changeset.md"));
    assert.equal(run("retire", "pr-feedback-add-a-changeset.md").status, 0);
    assert.equal(loadManifest(dir).rules["pr-feedback-add-a-changeset.md"].status, "retired");
    assert.equal(run("dismiss", "--title", "Use tabs", "--urls", "https://github.com/o/r/pull/9#issuecomment-9").status, 0);
    assert.deepEqual(loadManifest(dir).dismissed.map((d) => d.title), ["Use tabs"]);
    assert.equal(run("bogus").status, 1);
    assert.equal(run("record", "--generator", "magic", "x.md").status, 1);
  } finally {
    rmSync(dir, { recursive: true, force: true });
    rmSync(cache, { recursive: true, force: true });
  }
});

test("--force never replaces rules the manifest marks as plugin-written or edited", () => {
  const dir = mkdtempSync(join(tmpdir(), "rules-guard-"));
  try {
    const items = [1, 2, 3].map((n) => ({ sentence: "Avoid any types in handlers.", author: `r${n}`, pr: n, url: `https://github.com/o/r/pull/${n}`, path: "src/a.ts", kind: "prohibition" }));
    const cluster = { label: ["any", "types"], kind: "prohibition", kinds: ["prohibition"], items, occurrences: 3, distinctAuthors: 3, distinctPRs: 3, paths: ["src/a.ts"], authors: ["r1", "r2", "r3"] };
    const first = writeSkills([cluster], { targetDir: dir });
    const name = basename(first.written[0].path);
    recordFiles(dir, [name], { generator: "heuristic", now: new Date(NOW) });
    assert.equal(writeSkills([cluster], { targetDir: dir, force: true }).written.length, 1, "unedited heuristic rule: --force rewrites");
    recordFiles(dir, [name], { generator: "heuristic", now: new Date(NOW) });
    writeFileSync(first.written[0].path, `${readFileSync(first.written[0].path, "utf-8")}\nMy note.\n`);
    assert.equal(writeSkills([cluster], { targetDir: dir, force: true }).skipped.length, 1, "edited: kept");
    const m = loadManifest(dir);
    m.rules[name].generator = "learn-from-reviews";
    m.rules[name].sha256 = fileSha(readFileSync(first.written[0].path, "utf-8"));
    saveManifest(dir, m);
    assert.equal(writeSkills([cluster], { targetDir: dir, force: true }).skipped.length, 1, "plugin-written: kept");
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
