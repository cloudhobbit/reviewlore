import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { historyStats, findInstructionFiles } from "../lib/instructions.mjs";

function tree(files) {
  const root = mkdtempSync(join(tmpdir(), "instr-"));
  for (const [path, body] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), body);
  }
  return root;
}

test("findInstructionFiles finds instruction files, skips dependencies, marks generated rules", () => {
  const root = tree({
    "CLAUDE.md": "# root",
    "AGENTS.md": "agents",
    "packages/api/CLAUDE.md": "api",
    "packages/api/src/REVIEW.md": "review",
    "a/b/c/d/e/CLAUDE.md": "too deep",
    "node_modules/x/CLAUDE.md": "dependency",
    ".hidden/CLAUDE.md": "hidden",
    ".claude/rules/testing.md": "# Testing",
    ".claude/rules/deep/nested/more/style.md": "# Style",
    ".claude/rules/pr-feedback-add-a-changeset.md": '---\npaths:\n  - "src/**"\n---\n<!-- Generated by reviewlore (learn-from-reviews) from PR review history. -->\n# Add',
    ".claude/settings.json": "{}",
    ".github/copilot-instructions.md": "copilot",
    ".github/instructions/ts.instructions.md": "ts",
    ".github/workflows/ci.yml": "ci",
    "README.md": "readme",
  });
  try {
    const found = findInstructionFiles(root);
    assert.deepEqual(found.map((f) => f.path), [
      ".claude/rules/deep/nested/more/style.md",
      ".claude/rules/pr-feedback-add-a-changeset.md",
      ".claude/rules/testing.md",
      ".github/copilot-instructions.md",
      ".github/instructions/ts.instructions.md",
      "AGENTS.md",
      "CLAUDE.md",
      "packages/api/CLAUDE.md",
      "packages/api/src/REVIEW.md",
    ]);
    const byPath = Object.fromEntries(found.map((f) => [f.path, f]));
    assert.equal(byPath[".claude/rules/pr-feedback-add-a-changeset.md"].generated, true);
    assert.equal(byPath[".claude/rules/testing.md"].generated, false);
    assert.equal(byPath["CLAUDE.md"].bytes, 6);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("findInstructionFiles keeps the 50 largest files", () => {
  const files = {};
  for (let i = 0; i < 60; i++) files[`.claude/rules/r${String(i).padStart(2, "0")}.md`] = "x".repeat(i + 1);
  const root = tree(files);
  try {
    const found = findInstructionFiles(root);
    assert.equal(found.length, 50);
    assert.ok(!found.some((f) => f.path === ".claude/rules/r00.md"), "smallest dropped");
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

const comment = (author, pr, body = "Please add a test for the empty case here.") => ({
  type: "issue_comment", comment_id: Math.random(), pr_number: pr, author, author_type: "User", body,
  created_at: "2026-01-01T00:00:00Z", html_url: `https://github.com/o/r/pull/${pr}#issuecomment-1`,
});

test("historyStats counts human reviewers and PRs after the extraction filters", () => {
  const data = {
    meta: { pr_authors: { 1: "author" } },
    issue_comments: [
      comment("alice", 1), comment("bob", 2), comment("alice", 3),
      comment("author", 1),                                   // PR author on own PR
      { ...comment("dependabot[bot]", 4), author_type: "Bot" }, // bot
      comment("carol", 5, "LGTM"),                            // too short / praise
    ],
  };
  const h = historyStats(data);
  assert.equal(h.prs, 3);
  assert.equal(h.reviewers, 2);
  assert.equal(h.comments, 3);
  assert.equal(h.top_reviewer_share, 0.67);
  assert.equal(h.warning, "thin");
});

test("historyStats warns when one reviewer wrote most of the feedback", () => {
  const issue_comments = [];
  for (let pr = 1; pr <= 60; pr++) issue_comments.push(comment("maintainer", pr));
  for (const who of ["a", "b", "c"]) issue_comments.push(comment(who, 61));
  assert.equal(historyStats({ issue_comments }).warning, "single-reviewer");

  const balanced = [];
  for (let pr = 1; pr <= 60; pr++) balanced.push(comment(["a", "b", "c"][pr % 3], pr));
  const h = historyStats({ issue_comments: balanced });
  assert.equal(h.warning, null);
  assert.equal(h.prs, 60);
});
