import { test } from "node:test";
import assert from "node:assert/strict";
import { checkRule, indexCandidates, globToRegExp } from "../eval/skill/check-rules.mjs";

const CANDIDATES = {
  clusters: [
    {
      quotes: [
        { text: "Please add a changeset for this.", author: "alice", pr: 1, url: "https://github.com/o/r/pull/1#issuecomment-1", path: "src/api/a.ts" },
        { text: "This needs a changeset since it changes the CLI output.", author: "bob", pr: 2, url: "https://github.com/o/r/pull/2#discussion_r2", path: "src/cli/b.ts" },
        { text: "Missing changeset", author: "alice", pr: 3, url: "https://github.com/o/r/pull/3#issuecomment-3", path: "docs/guide.md" },
      ],
    },
  ],
};
const INDEX = indexCandidates(CANDIDATES);
const PROV = "<!-- Generated by reviewlore (learn-from-reviews) from PR review history. Review, edit or delete freely. -->";
const CITE_1 = "- > Please add a changeset\n  — @alice on PR #1: https://github.com/o/r/pull/1#issuecomment-1";
const CITE_2 = "- > This needs a changeset since it changes the CLI output.\n  — @bob on PR #2: https://github.com/o/r/pull/2#discussion_r2";

function rule({ front = '---\npaths:\n  - "src/**/*.ts"\n---\n', prov = PROV, cites = [CITE_1, CITE_2] } = {}) {
  return `${front}${prov}\n\n# Add a changeset\n\nAdd one.\n\n**Why:** Asked on 2 PRs.\n\n## Examples from PR review history\n\n${cites.join("\n")}\n`;
}
const checks = (text, name = "pr-feedback-add-a-changeset.md") => checkRule(text, name, INDEX).map((f) => f.check);

test("a well-formed rule passes", () => {
  assert.deepEqual(checkRule(rule(), "pr-feedback-add-a-changeset.md", INDEX), []);
  assert.deepEqual(checks(rule({ front: "" })), [], "unscoped rule");
});

test("name, provenance and frontmatter are enforced", () => {
  assert.ok(checks(rule(), "add-a-changeset.md").includes("name"));
  assert.ok(checks(rule({ prov: "<!-- hand written -->" })).includes("provenance"));
  assert.ok(checks(rule({ front: '---\npaths:\n  - "src/**"\ndescription: x\n---\n' })).includes("frontmatter"));
  assert.ok(checks(rule({ front: "---\npaths:\n  - src/**\n---\n" })).includes("frontmatter"), "unquoted glob");
});

test("citations must exist in the candidates file and match author and PR", () => {
  const unknown = "- > Please add a changeset\n  — @alice on PR #9: https://github.com/o/r/pull/9#issuecomment-9";
  assert.ok(checks(rule({ cites: [CITE_1, CITE_2, unknown] })).includes("citation-source"));
  const wrongAuthor = "- > Please add a changeset\n  — @mallory on PR #1: https://github.com/o/r/pull/1#issuecomment-1";
  assert.ok(checks(rule({ cites: [wrongAuthor, CITE_2] })).includes("citation-source"));
  const badFormat = "- > Please add a changeset\n  — alice, PR 1";
  assert.ok(checks(rule({ cites: [badFormat, CITE_2] })).includes("citation-format"));
});

test("quotes must be verbatim (whitespace aside)", () => {
  const edited = "- > Please always add a changeset\n  — @alice on PR #1: https://github.com/o/r/pull/1#issuecomment-1";
  assert.ok(checks(rule({ cites: [edited, CITE_2] })).includes("verbatim"));
  const wrapped = "- > This needs a changeset since it\n  > changes the CLI output.\n  — @bob on PR #2: https://github.com/o/r/pull/2#discussion_r2";
  assert.deepEqual(checks(rule({ cites: [CITE_1, wrapped] })), []);
});

test("evidence bar: two PRs and two reviewers", () => {
  assert.ok(checks(rule({ cites: [CITE_1] })).includes("citations"));
  const samePerson = "- > Missing changeset\n  — @alice on PR #3: https://github.com/o/r/pull/3#issuecomment-3";
  const fails = checkRule(rule({ cites: [CITE_1, samePerson] }), "pr-feedback-x.md", INDEX);
  assert.ok(fails.some((f) => f.check === "evidence" && /reviewer/.test(f.detail)));
});

test("scope: valid globs, never docs-only for comments on source", () => {
  assert.ok(checks(rule({ front: '---\npaths:\n  - "src/[ab]/*.ts"\n---\n' })).includes("scope"));
  assert.ok(checks(rule({ front: '---\npaths:\n  - "docs/**/*.md"\n---\n' })).includes("scope"));
  assert.ok(checks(rule({ front: '---\npaths:\n  - ".changeset/*.md"\n---\n' })).includes("scope"));
  // Scoped to the triggering source code although a comment was on docs: fine.
  const onDocs = "- > Missing changeset\n  — @alice on PR #3: https://github.com/o/r/pull/3#issuecomment-3";
  assert.deepEqual(checks(rule({ front: '---\npaths:\n  - "lib/**/*.ts"\n---\n', cites: [onDocs, CITE_2] })), []);
});

test("an anonymised rule may not contain @logins", () => {
  const prov = "<!-- Generated by reviewlore (learn-from-reviews), anonymised. -->";
  assert.ok(checks(rule({ prov })).includes("anonymised"));
});

test("globToRegExp", () => {
  assert.ok(globToRegExp("src/**/*.ts").test("src/a/b/c.ts"));
  assert.ok(globToRegExp("src/**/*.ts").test("src/c.ts"));
  assert.ok(!globToRegExp("src/*.ts").test("src/a/c.ts"));
  assert.ok(globToRegExp("packages/*/src/**/*.{ts,tsx}").test("packages/x/src/y.tsx"));
  assert.ok(globToRegExp("src/[ab].ts").test("src/b.ts"), "classes match (hand-written rules use them)");
  assert.equal(globToRegExp("src/[!a].ts"), null, "negation is rejected");
  assert.equal(globToRegExp(""), null);
});
