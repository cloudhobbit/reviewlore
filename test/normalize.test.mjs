import { test } from "node:test";
import assert from "node:assert/strict";
import { stripMarkdown, splitSentences, isNoise, looksLikeAIReview } from "../lib/normalize.mjs";

test("stripMarkdown removes fenced code, inline code, URLs, mentions", () => {
  const input = "Please use `Foo` instead of ```js\nbar()\n``` see https://x.y/path cc @alice";
  const out = stripMarkdown(input);
  assert.equal(out.includes("```"), false);
  assert.equal(out.includes("https://"), false);
  assert.equal(out.includes("@alice"), false);
  assert.match(out, /Please use\s+instead of/);
});

test("splitSentences splits on punctuation and newlines", () => {
  const s = splitSentences("First. Second!\nThird?");
  assert.deepEqual(s, ["First.", "Second!", "Third?"]);
});

test("isNoise detects bots by author_type", () => {
  assert.equal(isNoise({ author: "dependabot", author_type: "Bot", body: "Bumps lodash" }), true);
});

test("isNoise detects bot-name patterns", () => {
  assert.equal(isNoise({ author: "github-actions[bot]", body: "Some long enough body here" }), true);
});

test("isNoise drops short comments", () => {
  assert.equal(isNoise({ author: "alice", body: "lgtm" }), true);
});

test("isNoise drops praise-only comments", () => {
  assert.equal(isNoise({ author: "alice", body: "LGTM! Looks good to me, thanks for the fix." }), false);
  assert.equal(isNoise({ author: "alice", body: "👍" }), true);
});

test("isNoise keeps substantive comments", () => {
  const c = {
    author: "alice",
    body: "Please avoid using `any` here — we should prefer unknown.",
  };
  assert.equal(isNoise(c), false);
});

test("isNoise uses raw body length, not stripped (regression: #5)", () => {
  // After stripping inline code this would be ~9 chars and would falsely be
  // marked noise — but raw body is 24 chars, so it should be kept.
  const c = {
    author: "alice",
    body: "Use `foo()` not `bar()`.",
  };
  assert.equal(isNoise(c), false);
});

test("stripMarkdown keepInlineCode keeps backtick spans but still drops fenced code", () => {
  const out = stripMarkdown("Use `unknown` not `any`.\n```js\nconst x = 1\n```", { keepInlineCode: true });
  assert.match(out, /Use `unknown` not `any`\./);
  assert.equal(out.includes("const x"), false);
});

test("isNoise treats bot accounts registered as users as bots", () => {
  assert.equal(isNoise({ author: "codecov-commenter", author_type: "User", body: "Codecov Report: all modified lines covered" }), true);
});

test("stripMarkdown keeps link text, drops images and HTML tags", () => {
  const out = stripMarkdown('We [generally](https://x.y/a) don\'t accept it. ![img](https://x.y/i.png) <img width="5" src="u" /> ok');
  assert.equal(out, "We generally don't accept it. ok");
});

test("stripMarkdown keepInlineCode leaves @scopes and URLs inside code spans alone", () => {
  const out = stripMarkdown("Add `@pnpm/plugin-commands-sbom` to it, cc @alice", { keepInlineCode: true });
  assert.equal(out, "Add `@pnpm/plugin-commands-sbom` to it, cc");
});


test("stripMarkdown keeps generics — only real HTML tags are removed", () => {
  assert.equal(stripMarkdown("Prefer Promise<void> over any here <br/> ok"), "Prefer Promise<void> over any here ok");
  assert.equal(stripMarkdown("Don't use Map<string, number> here"), "Don't use Map<string, number> here");
});

test("stripMarkdown keeps a link whose text is inline code", () => {
  const out = stripMarkdown("Please use [`useEffect`](https://react.dev/x) for this.", { keepInlineCode: true });
  assert.equal(out, "Please use `useEffect` for this.");
});

test("stripMarkdown keeps list items as separate lines; single backticks spanning lines are code", () => {
  const out = stripMarkdown("A few things\n- Add a test for the parser\n* Rename this helper\n1. Remove the logging\n`\nconsole.log(x)\n`\nend");
  assert.deepEqual(splitSentences(out), ["A few things", "Add a test for the parser", "Rename this helper", "Remove the logging", "end"]);
});

test("looksLikeAIReview: signature at the top, or report labels with a severity marker", () => {
  assert.equal(looksLikeAIReview("**Acme Review** (powered by GPT-5 on Acme Cloud)\n## Summary\nThis PR…"), "signature");
  assert.equal(looksLikeAIReview("🤖 Automated review\nLooks fine."), "signature");
  assert.equal(
    looksLikeAIReview("Notes on the change.\n**Recommendation:** split the PR.\nSeverity: high"),
    "report-labels",
  );
  // Humans: a signature phrase deep in the text, AI talk, or a bold label alone.
  assert.equal(looksLikeAIReview(`${"x".repeat(250)} this description was generated by an AI model`), null);
  assert.equal(looksLikeAIReview("Please stop sending AI review spam PRs."), null);
  assert.equal(looksLikeAIReview("**Summary:** rename the helper and add a test."), null);
  assert.equal(isNoise({ author: "someone", author_type: "User", body: "🤖 Automated review: consider adding tests here." }), true);
});


test("looksLikeAIReview: leading priority tag or an 'Automated review' sentence", () => {
  assert.equal(looksLikeAIReview("[P2] Keep normalizing typed-array views\n\nThis branch skips…"), "priority-tag");
  assert.equal(looksLikeAIReview("**[P1] Handle the empty case**\n\nWhen the list…"), "priority-tag");
  assert.equal(looksLikeAIReview("Please preserve the conversion.\n\nAutomated review. Reproduced on Node 24."), "automated-review");
  // Humans mentioning these words mid-sentence aren't flagged.
  assert.equal(looksLikeAIReview("This fixes the [P2] item from the triage list."), null);
  assert.equal(looksLikeAIReview("We could add an automated review step to CI later."), null);
});
