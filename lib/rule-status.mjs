// `reviewlore rules status`: is each generated rule still backed by review
// history, and still about code that exists? (docs/plans/10-keeping-rules-fresh.md)
//
// It only flags. Age alone is never a reason to retire: pnpm's most
// important rule ("add a changeset") had no citation newer than six
// months when this was written. Support counts come from word matching, so
// they are approximate; the learn-from-reviews skill reads the quotes and
// decides with the user.

import { readFileSync, existsSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { parseRuleFile } from "./rule-files.mjs";
import { fileSha } from "./rules-manifest.mjs";
import { searchIndex } from "./review-index.mjs";
import { classifySentence, tokenize } from "./patterns.mjs";
import { polarity } from "./cluster.mjs";
import { globToRegExp } from "./globs.mjs";

const DAY = 86_400_000;
const NEGATIVE_TITLE_RE = /^(?:don'?t|do not|avoid|never|no\b|stop)/i;
const ASKS = new Set(["request", "prohibition", "prescription"]);

// The title words the rule's own quotes also use: its topic ("changeset"),
// not incidental title words ("ships"). The title if they share none.
function topicWords(title, examples) {
  const quoted = new Set(examples.flatMap((e) => tokenize(e.quote)));
  const shared = tokenize(title).filter((t) => quoted.has(t));
  return shared.length ? shared.join(" ") : title;
}

const hitPolarity = (text) => {
  const c = classifySentence(text);
  return c ? polarity(c) : "positive";
};

// Rule files reviewlore wrote that the manifest doesn't know.
function unmanagedFiles(targetDir, manifest) {
  const dir = join(targetDir, ".claude", "rules");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => /^pr-feedback-.+\.md$/.test(f) && !manifest.rules[f])
    .filter((f) => readFileSync(join(dir, f), "utf-8").includes("<!-- Generated by reviewlore"))
    .sort();
}

// tracked: repo file paths (git ls-files). index: lib/review-index.mjs
// index, or null when there's no review history.
export function ruleStatus({ targetDir, manifest, index, tracked, months = 6, now = Date.now() }) {
  const cutoff = now - months * 30.44 * DAY;
  const rules = [];
  for (const [file, entry] of Object.entries(manifest.rules).sort(([a], [b]) => (a < b ? -1 : 1))) {
    if (entry.status === "retired") continue;
    const path = join(targetDir, ".claude", "rules", file);
    const r = { file, title: entry.title ?? file, generator: entry.generator, flags: [] };
    if (!existsSync(path)) {
      r.flags.push("missing");
      r.suggest = "dismiss";
      rules.push(r);
      continue;
    }
    const text = readFileSync(path, "utf-8");
    const parsed = parseRuleFile(text, file);
    if (parsed?.title) r.title = parsed.title;
    if (fileSha(text) !== entry.sha256) r.flags.push("edited");

    // Paths that no longer match any tracked file.
    const globs = parsed?.paths ?? entry.globs ?? [];
    if (globs.length) {
      const dead = globs.filter((g) => {
        const re = globToRegExp(g);
        return !re || !tracked.some((f) => re.test(f));
      });
      if (dead.length === globs.length) r.flags.push("paths-gone");
      else if (dead.length) r.flags.push("paths-partial");
      if (dead.length) r.dead_globs = dead;
    }

    // Cited evidence older than the window: informational.
    const dated = (entry.evidence ?? []).filter((e) => e.at);
    if (dated.length && dated.every((e) => Date.parse(e.at) < cutoff)) r.flags.push("evidence-aged-out");

    // Fresh support and contradictions in the window, by word search.
    if (index) {
      const ruleNegative = NEGATIVE_TITLE_RE.test(r.title);
      const res = globs.map(globToRegExp).filter(Boolean);
      const hits = searchIndex(index, entry.query ?? topicWords(r.title, parsed?.examples ?? []), { limit: 50, requireRarest: true }).results
        .filter((h) => Date.parse(h.created_at) >= cutoff && ASKS.has(h.kind))
        .filter((h) => !h.path || !res.length || res.some((re) => re.test(h.path)));
      const same = hits.filter((h) => (hitPolarity(h.quote) === "negative") === ruleNegative);
      const opposite = hits.filter((h) => (hitPolarity(h.quote) === "negative") !== ruleNegative);
      r.recent_support = {
        prs: new Set(same.map((h) => h.pr)).size,
        reviewers: new Set(same.map((h) => h.author)).size,
        latest: same.map((h) => h.created_at).sort().at(-1)?.slice(0, 10) ?? null,
        urls: same.slice(0, 3).map((h) => h.url),
      };
      if (r.recent_support.prs === 0) r.flags.push("no-recent-support");
      // Only with a recorded query: from title words alone, "Fix bugs at
      // their root cause" matched every comment about a fix.
      if (entry.query && new Set(opposite.map((h) => h.author)).size >= 2) {
        r.flags.push("contradiction-candidates");
        r.contradictions = opposite.slice(0, 5).map((h) => ({ quote: h.quote, author: h.author, url: h.url }));
      }
    }

    // Contradictions are word-matched candidates: they ask for a look, never
    // for retirement on their own.
    r.suggest = r.flags.includes("paths-gone")
      ? "review-retire"
      : r.flags.includes("contradiction-candidates")
        ? "check"
        : r.flags.includes("paths-partial") || (r.flags.includes("evidence-aged-out") && r.recent_support?.prs > 0)
          ? "update"
          : "keep";
    rules.push(r);
  }
  const unmanaged = unmanagedFiles(targetDir, manifest);
  const count = (s) => rules.filter((r) => r.suggest === s).length;
  return {
    rules,
    unmanaged,
    stats: {
      rules: rules.length,
      keep: count("keep"),
      update: count("update"),
      review_retire: count("review-retire"),
      check: count("check"),
      dismiss: count("dismiss"),
      unmanaged: unmanaged.length,
    },
  };
}

const SUGGEST = { keep: "keep", update: "update: refresh quotes", "review-retire": "review: retire?", check: "check contradictions", dismiss: "deleted: dismiss" };

export function renderStatus(status, { repo, source, ageDays, months }) {
  const lines = [
    `# Review rules status — ${repo}`,
    "",
    source
      ? `Review history: ${source}, ${ageDays ?? "?"} days old; window ${months} months.`
      : "No review history available: only files and paths were checked.",
    "",
  ];
  if (!status.rules.length && !status.unmanaged.length) {
    lines.push("No rules generated by reviewlore yet.");
    return `${lines.join("\n")}\n`;
  }
  if (status.rules.length) {
    lines.push("| Rule | Suggestion | Recent support | Notes |", "|---|---|---|---|");
    for (const r of status.rules) {
      const s = r.recent_support;
      const support = s ? `${s.prs} PRs / ${s.reviewers} reviewers${s.latest ? ` (latest ${s.latest})` : ""}` : "—";
      const notes = r.flags.filter((f) => f !== "no-recent-support").join(", ") || "";
      lines.push(`| ${r.title} (\`${r.file}\`) | ${SUGGEST[r.suggest]} | ${support} | ${notes} |`);
    }
    lines.push("");
  }
  for (const r of status.rules.filter((x) => x.contradictions)) {
    lines.push(`**Possible contradictions for ${r.file}:**`);
    for (const c of r.contradictions) lines.push(`- "${c.quote}" — @${c.author}: ${c.url}`);
    lines.push("");
  }
  if (status.unmanaged.length) {
    lines.push(`Not tracked yet (written before 0.3): ${status.unmanaged.map((f) => `\`${f}\``).join(", ")}. Run \`reviewlore rules record\` on them.`, "");
  }
  lines.push(
    "Support counts are approximate (word matching). Nothing is changed automatically: re-run the learn-from-reviews skill to refresh, update or retire rules with your approval.",
  );
  return `${lines.join("\n")}\n`;
}
