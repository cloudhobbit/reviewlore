// Inputs for the skill's judgement (docs/plans/15-rule-specificity-and-conflicts.md):
//   - historyStats: how much human review history there is, so the skill
//     can warn before proposing rules from too little;
//   - findInstructionFiles: the repo's existing instruction files, so the
//     skill can label each proposed rule NEW / DUPLICATE / VIOLATED /
//     CONTRADICTS against what's already written down.
// The CLI only discovers and counts; the model reads and judges.

import { readdirSync, statSync, openSync, readSync, closeSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { applySignals } from "./signals.mjs";
import { isNoise } from "./normalize.mjs";

// Thresholds for `history.warning` (plan 15; the 50-PR figure is from a
// public write-up of a similar approach, not calibrated here yet).
export const THIN_PRS = 50;
export const THIN_REVIEWERS = 3;
export const SINGLE_REVIEWER_SHARE = 0.8;

// Human review comments in the window, after the same filters extraction
// uses: plain issues, PR authors' own comments and resolved threads
// (applySignals), then bots, AI-written reviews and short praise (isNoise).
export function historyStats(data) {
  const enriched = applySignals(data);
  const byAuthor = new Map();
  const prs = new Set();
  let comments = 0;
  for (const c of [
    ...(enriched.issue_comments ?? []),
    ...(enriched.review_comments ?? []),
    ...(enriched.review_submissions ?? []),
  ]) {
    if (isNoise(c)) continue;
    comments++;
    if (c.pr_number != null) prs.add(c.pr_number);
    byAuthor.set(c.author, (byAuthor.get(c.author) ?? 0) + 1);
  }
  const top = Math.max(0, ...byAuthor.values());
  const share = comments ? Math.round((top / comments) * 100) / 100 : 0;
  let warning = null;
  if (prs.size < THIN_PRS || byAuthor.size < THIN_REVIEWERS) warning = "thin";
  else if (share >= SINGLE_REVIEWER_SHARE) warning = "single-reviewer";
  return { prs: prs.size, reviewers: byAuthor.size, comments, top_reviewer_share: share, warning };
}

const NAMED = new Set(["CLAUDE.md", "CLAUDE.local.md", "AGENTS.md", "REVIEW.md"]);
const SKIP_DIRS = new Set(["node_modules", ".git", "vendor", "dist", "build", "coverage", "target", ".next", ".venv"]);
const MAX_ENTRIES = 50;
const PROVENANCE = "<!-- Generated by reviewlore";

function head(path, bytes = 2048) {
  const fd = openSync(path, "r");
  try {
    const buf = Buffer.alloc(bytes);
    const n = readSync(fd, buf, 0, bytes, 0);
    return buf.subarray(0, n).toString("utf-8");
  } finally {
    closeSync(fd);
  }
}

function isInstructionFile(rel) {
  const parts = rel.split("/");
  const name = parts[parts.length - 1];
  if (NAMED.has(name)) return true;
  if (rel === ".github/copilot-instructions.md") return true;
  if (parts[0] === ".github" && parts[1] === "instructions" && name.endsWith(".instructions.md")) return true;
  // .claude/rules/** at any depth (nested .claude dirs in a monorepo too).
  const i = parts.indexOf(".claude");
  return i !== -1 && parts[i + 1] === "rules" && name.endsWith(".md");
}

// Instruction files under rootDir: CLAUDE.md / AGENTS.md / REVIEW.md at any
// depth ≤ maxDepth, .claude/rules/**/*.md, Copilot instructions. Paths use
// "/" on every platform. At most 50 entries (largest kept), sorted by path.
// `generated` marks rule files this tool wrote.
export function findInstructionFiles(rootDir, { maxDepth = 4 } = {}) {
  const found = [];
  const walk = (dir, depth) => {
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      const full = join(dir, e.name);
      const rel = relative(rootDir, full).split(sep).join("/");
      if (e.isDirectory()) {
        if (SKIP_DIRS.has(e.name)) continue;
        // Hidden directories hold no instructions, except these two.
        if (e.name.startsWith(".") && e.name !== ".claude" && e.name !== ".github") continue;
        // Rule directories can nest deeper than the depth limit.
        const inRules = rel.split("/").includes("rules");
        if (depth < maxDepth || inRules) walk(full, depth + 1);
      } else if (e.isFile() && isInstructionFile(rel)) {
        const bytes = statSync(full).size;
        const generated = rel.split("/").includes(".claude") && head(full).includes(PROVENANCE);
        found.push({ path: rel, bytes, generated });
      }
    }
  };
  walk(rootDir, 0);
  return found
    .sort((a, b) => b.bytes - a.bytes)
    .slice(0, MAX_ENTRIES)
    .sort((a, b) => a.path.localeCompare(b.path));
}

// Why nothing cleared the bar (≥ 2 PRs and ≥ 2 reviewers), with numbers,
// and what to try, most useful first (docs/plans/08). Never suggests
// lowering the bar quietly: each option is explicit and labelled.
//   → { reasons: [string], suggestions: [{ text, skill?, cli? }] }
export function diagnoseEmpty(history, { months = 6, singleReviewer = false } = {}) {
  const pct = Math.round(history.top_reviewer_share * 100);
  const nextWindow = months < 12 ? 12 : 24;
  const reasons = [];
  const longer = months < 24
    ? { text: `Look further back: ${nextWindow} months.`, skill: `use ${nextWindow} months`, cli: `--months ${nextWindow}` }
    : null;
  const single = {
    text: "Single-maintainer repo? Include the maintainer's own recurring requests, labelled as maintainer preferences (3+ PRs from one reviewer).",
    skill: "/reviewlore:learn-from-reviews single-maintainer",
    cli: "--single-reviewer",
  };
  const zero = { text: "Zero can be the right answer: there may be no recurring conventions to learn yet." };
  let suggestions;
  if (history.prs < THIN_PRS) {
    reasons.push(`Only ${history.prs} PR${history.prs === 1 ? "" : "s"} had human review in the last ${months} months — too few for conventions to recur.`);
    suggestions = [longer, history.reviewers < THIN_REVIEWERS || history.warning === "single-reviewer" ? single : null, zero];
  } else if (history.reviewers < THIN_REVIEWERS || history.warning === "single-reviewer") {
    reasons.push(history.reviewers < THIN_REVIEWERS
      ? `Only ${history.reviewers} ${history.reviewers === 1 ? "person" : "people"} reviewed PRs in the last ${months} months, and a rule needs at least 2 reviewers.`
      : `${history.prs} PRs had human review in the last ${months} months, but one reviewer wrote ${pct}% of it, and a rule needs at least 2 reviewers.`);
    suggestions = [single, longer, zero];
  } else {
    reasons.push(`${history.prs} PRs from ${history.reviewers} reviewers in the last ${months} months, but no request recurred on 2+ PRs from 2+ reviewers.`);
    suggestions = [
      zero,
      { text: "The Claude Code plugin also merges requests worded differently, which word matching keeps apart.", skill: "/reviewlore:learn-from-reviews" },
      { text: "Explore what's below the bar (not for committing as-is).", cli: "--preset exploratory" },
    ];
  }
  // Already in single-maintainer mode: don't suggest it again.
  return { reasons, suggestions: suggestions.filter((x) => x && !(singleReviewer && x === single)) };
}

// The diagnosis as CLI text.
export function explainEmptyResult(history, opts = {}) {
  const d = diagnoseEmpty(history, opts);
  const steps = d.suggestions.map((s) => `  • ${s.text}${s.cli ? ` (${s.cli})` : ""}`);
  return `${d.reasons.join(" ")}\nNext steps:\n${steps.join("\n")}`;
}
