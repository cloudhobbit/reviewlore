// Render clusters into Claude Code rule files (.claude/rules/*.md).
//
// Claude Code reads exactly one frontmatter field from a rule: `paths`
// (globs the rule applies to). A rule without it loads in every session,
// so we emit `paths` whenever the source comments were on files, and no
// frontmatter otherwise. Everything else lives in the markdown body.

import { loadManifest, fileSha } from "./rules-manifest.mjs";
import { writeFileSync, mkdirSync, existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { pickExamples } from "./extract.mjs";
import { pathGlobs } from "./renderers/_common.mjs";

// Rules written by the plugin's learn-from-reviews skill carry this marker.
const isPluginRule = (text) => text.includes("reviewlore (learn-from-reviews)");

// A heuristic run never replaces, even with --force: rules the plugin wrote
// (by provenance or by the manifest), and recorded rules edited since.
function isProtected(targetDir, filename, text) {
  if (isPluginRule(text)) return true;
  const entry = loadManifest(targetDir)?.rules?.[filename];
  if (!entry) return false;
  return !entry.generator.startsWith("heuristic") || fileSha(text) !== entry.sha256;
}

const PROVENANCE =
  "<!-- Generated by reviewlore from PR review history. Review, edit or delete freely. -->";

function frontmatter(cluster) {
  const globs = pathGlobs(cluster.paths ?? []);
  if (globs.length === 0) return "";
  return `---\npaths:\n${globs.map((g) => `  - ${yamlQuote(g)}`).join("\n")}\n---\n\n`;
}

const quoteLines = (cluster) =>
  pickExamples(cluster.items, 3)
    .map((i) => `- > ${i.sentence}\n  — @${i.author} on PR #${i.pr ?? "?"}: ${i.url}`)
    .join("\n");

// Quote a string for use as a YAML scalar value. Collapses internal whitespace
// (including newlines) to single spaces and escapes embedded backslashes and
// double-quotes. Always returns a double-quoted scalar — safe regardless of
// colons, hash signs, or other YAML-sensitive characters in the input.
export function yamlQuote(value) {
  const collapsed = String(value).replace(/\s+/g, " ").trim();
  const escaped = collapsed.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  return `"${escaped}"`;
}

function slugify(tokens) {
  const slug = tokens
    .join("-")
    .replace(/[^a-z0-9-]/g, "")
    .replace(/-+/g, "-")
    .slice(0, 60)
    .replace(/^-+|-+$/g, ""); // a name that ends in "-" can't be read back (rule-files NAME_RE)
  return slug || "rule";
}

function pickRepresentativeSentence(items) {
  // Prefer the shortest non-trivial sentence — usually the cleanest statement.
  return [...items]
    .filter((i) => i.sentence.length >= 25 && i.sentence.length <= 200)
    .sort((a, b) => a.sentence.length - b.sentence.length)[0]?.sentence
    ?? items[0].sentence;
}

const KIND_WORDS = { prohibition: "avoid", prescription: "follow", request: "address" };

function chooseKindWord(cluster) {
  if (cluster.kind) return KIND_WORDS[cluster.kind] ?? "consider";
  const kinds = cluster.kinds ?? [];
  if (kinds.includes("prohibition")) return "avoid";
  if (kinds.includes("prescription")) return "follow";
  if (kinds.includes("request")) return "address";
  return "consider";
}

// LLM-rendered variant: prefer the synthesised name/rule/why/when_to_apply
// when present; fall back to heuristic rendering otherwise.
// A rule backed by one reviewer (single-maintainer mode, docs/plans/08) says
// so in its title and body: it's a preference, not a team convention yet.
const MAINTAINER = "Maintainer preference: ";
const singleReviewer = (cluster) => cluster.distinctAuthors === 1;
function supportLine(cluster) {
  return singleReviewer(cluster)
    ? `\n**Support:** one reviewer (@${cluster.authors?.[0] ?? "?"}) on ${cluster.distinctPRs} PRs — below the team bar of 2 reviewers. Review before relying on it.\n`
    : "";
}

export function renderLLMRule(cluster, synth) {
  if (!synth || synth._error || synth.name === "INCOHERENT") {
    // Fall back to heuristic rendering so a partial failure still produces
    // a useful file. Annotate the failure inline so the user can see what
    // happened (and decide whether to delete).
    const heur = renderRule(cluster);
    const note = synth?._error
      ? `\n\n<!-- LLM synthesis failed: ${synth._error.replace(/-->/g, "-- >")} -->`
      : synth?.name === "INCOHERENT"
        ? `\n\n<!-- LLM marked this cluster INCOHERENT — review carefully -->`
        : "";
    return { slug: heur.slug, body: heur.body + note };
  }

  const slug = slugify(synth.name.toLowerCase().split(/\s+/).slice(0, 6));
  const body = `${frontmatter(cluster)}${PROVENANCE}
<!-- Rule text synthesised by Claude from the quotes below. -->

# ${singleReviewer(cluster) ? MAINTAINER : ""}${synth.name}

${synth.rule}
${supportLine(cluster)}
**Why:** ${synth.why}

**How to apply:** ${synth.when_to_apply}

## Examples from PR review history

Synthesised from ${cluster.occurrences} comments by ${cluster.distinctAuthors} reviewers across ${cluster.distinctPRs} PRs:

${quoteLines(cluster)}
`;
  return { slug, body };
}

export function renderRule(cluster) {
  const label = cluster.label.join(" / ") || "review-pattern";
  const slug = slugify(cluster.label);
  const rep = pickRepresentativeSentence(cluster.items);
  const globs = pathGlobs(cluster.paths ?? []);
  const kindWord = chooseKindWord(cluster);

  // Same globs as the `paths:` frontmatter, so the prose can't disagree.
  const applyScope =
    globs.length > 0
      ? `When editing files matching: ${globs.map((g) => `\`${g}\``).join(", ")}`
      : "When editing any file in this repo";

  const title = `${singleReviewer(cluster) ? MAINTAINER : ""}${kindWord[0].toUpperCase()}${kindWord.slice(1)}: ${label}`;
  const body = `${frontmatter(cluster)}${PROVENANCE}

# ${title}

Reviewer feedback recurring ${cluster.occurrences}× across ${cluster.distinctAuthors} reviewers and ${cluster.distinctPRs} PRs:

> ${rep}
${supportLine(cluster)}
**Why:** This guidance recurred ${cluster.occurrences} times across ${cluster.distinctAuthors} distinct reviewers (${cluster.authors
    .slice(0, 5)
    .map((a) => `@${a}`)
    .join(", ")}${cluster.authors.length > 5 ? ", …" : ""}) on ${cluster.distinctPRs} different PRs. When multiple reviewers say the same thing, it usually reflects a real convention — not a one-off preference.

**How to apply:** ${applyScope}. Before submitting changes, check whether this rule applies and adjust accordingly.

## Examples from PR review history

${quoteLines(cluster)}
`;
  return { slug, body };
}

export function writeSkills(
  clusters,
  { targetDir, dryRun = false, force = false, synth = null } = {},
) {
  const rulesDir = join(targetDir, ".claude", "rules");
  if (!dryRun) mkdirSync(rulesDir, { recursive: true });

  const written = [];
  const skipped = [];
  const seenSlugs = new Set();
  for (let idx = 0; idx < clusters.length; idx++) {
    const cluster = clusters[idx];
    const { slug, body } = synth
      ? renderLLMRule(cluster, synth[idx])
      : renderRule(cluster);
    let finalSlug = slug;
    let n = 2;
    while (seenSlugs.has(finalSlug)) finalSlug = `${slug}-${n++}`;
    seenSlugs.add(finalSlug);
    const filename = `pr-feedback-${finalSlug}.md`;
    const path = join(rulesDir, filename);
    if (!dryRun) {
      // Don't silently clobber a rule the user may have hand-edited.
      // Pass force:true to overwrite (e.g. when re-running with new data) —
      // except rules the Claude Code plugin wrote: a heuristic run never
      // replaces those, even with --force.
      if (existsSync(path) && (!force || isProtected(targetDir, filename, readFileSync(path, "utf-8")))) {
        skipped.push({ path, slug: finalSlug, occurrences: cluster.occurrences });
        continue;
      }
      writeFileSync(path, body, "utf-8");
    }
    written.push({ path, slug: finalSlug, occurrences: cluster.occurrences });
  }
  return { written, skipped };
}

export function renderSummary(clusters, meta) {
  const lines = [
    `# PR-feedback skill generation summary`,
    ``,
    `Source: ${meta.owner}/${meta.repo}`,
    `Window: last ${meta.months_back} months (since ${meta.since})`,
    `Clusters extracted: ${clusters.length}`,
    ``,
  ];
  for (const c of clusters) {
    lines.push(
      `- **${c.label.join(" / ") || "(unlabelled)"}** — ${c.occurrences}× across ${c.distinctAuthors} authors, ${c.distinctPRs} PRs`,
    );
  }
  return lines.join("\n") + "\n";
}
