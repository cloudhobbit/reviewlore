// Text normalization: strip markdown code blocks, inline code, URLs, mentions,
// and HTML comments. Returns clean plaintext suitable for pattern extraction.
//
// Pass { keepInlineCode: true } to keep `inline code` spans: reviewers name
// the thing they're talking about in backticks ("Use `unknown` not `any`"),
// so dropping them loses both the topic tokens and a readable quote.

const FENCED_CODE = /```[\s\S]*?```/g;
// Single backticks wrapped around several lines are a code block too.
// Backticks pair up in order, so walk them rather than regex-match (a
// regex happily pairs one span's closing tick with the next one's opener).
function dropMultilineCode(text) {
  const parts = text.split("`");
  let out = parts[0];
  for (let i = 1; i < parts.length; i += 2) {
    const closed = i + 1 < parts.length;
    if (closed && parts[i].includes("\n")) out += " ";
    else out += closed ? `\`${parts[i]}\`` : `\`${parts[i]}`;
    if (closed) out += parts[i + 1];
  }
  return out;
}
const INLINE_CODE = /`[^`\n]+`/g;
const INLINE_CODE_SPLIT = /(`[^`\n]+`)/;
const MD_IMAGE = /!\[[^\]]*\]\([^)]*\)/g;
const MD_LINK = /\[([^\]]*)\]\([^)]*\)/g;
// Only tags GitHub comments actually contain — a generic like Promise<void>
// or Map<string, number> must survive.
const HTML_TAG =
  /<\/?(?:img|br|hr|p|div|span|a|b|i|em|strong|code|pre|sub|sup|kbd|details|summary|table|thead|tbody|tr|td|th|ul|ol|li|h[1-6]|picture|source|video)\b[^>]*>/gi;
const URL_RE = /https?:\/\/\S+/g;
const MENTION_RE = /@[a-zA-Z0-9_-]+/g;
const HTML_COMMENT = /<!--[\s\S]*?-->/g;
const QUOTE_LINE = /^\s*>.*$/gm;
// Bullets and numbered items start a new sentence ("- Add a test\n- Rename…").
const LIST_MARKER = /^[ \t]*(?:[-*+]|\d+[.)])[ \t]+/gm;
const INLINE_SPACE = /[ \t\f\v\r]+/g;
const BLANK_LINES = /\n\s*\n+/g;

// Prose-only cleanup between code spans: HTML tags, bare URLs and
// @mentions go. (Images and links are handled before the split, since a
// link's text can itself be code: [`useEffect`](https://…).)
const cleanProse = (text) =>
  text
    .replace(HTML_TAG, " ")
    .replace(URL_RE, " ")
    .replace(MENTION_RE, " ");

export function stripMarkdown(body, { keepInlineCode = false } = {}) {
  if (!body) return "";
  const withoutBlocks = dropMultilineCode(body.replace(FENCED_CODE, " "))
    .replace(HTML_COMMENT, " ")
    .replace(FENCED_CODE, " ")
    .replace(QUOTE_LINE, " ")
    .replace(MD_IMAGE, " ")
    .replace(MD_LINK, "$1")
    .replace(LIST_MARKER, "\n");
  // With inline code kept, clean only the prose between code spans, so
  // `@scope/pkg` or a URL inside backticks survives intact.
  const text = keepInlineCode
    ? withoutBlocks.split(INLINE_CODE_SPLIT).map((seg, i) => (i % 2 ? seg : cleanProse(seg))).join("")
    : cleanProse(withoutBlocks.replace(INLINE_CODE, " "));
  // Keep line breaks (splitSentences uses them); collapse everything else.
  return text
    .replace(INLINE_SPACE, " ")
    .replace(BLANK_LINES, "\n")
    .split("\n").map((l) => l.trim()).filter(Boolean).join("\n")
    .trim();
}

// Split a comment body into "sentences" (rough — split on . ! ? and newlines).
export function splitSentences(text) {
  return text
    .split(/(?<=[.!?])\s+|\n+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
}

// Heuristic noise filter: skip bot comments, very short, pure praise.
const BOT_USER_TYPES = new Set(["Bot"]);
// GitHub marks most bots with author_type "Bot"; these post as ordinary
// user accounts, so match them by name.
const BOT_NAME_RE =
  /(\[bot\]|-bot$|^dependabot|^renovate|^github-actions|^codecov-commenter$|^coveralls$|^sonarcloud$|^sonarqubecloud$)/i;
const PRAISE_RE = /^(lgtm|looks good|nice|👍|👌|🎉|thanks|thank you|🚀|nit:?\s*$)\.?\s*$/i;

// AI reviewers posting from ordinary user accounts (GitHub doesn't mark
// them as bots). Deliberately strict — see docs/plans/13: a signature in
// the opening 200 characters, or a bold report label together with a
// severity marker. Looser signals (long report structure, "AI review"
// anywhere) also matched human comments, so they're not used. Measured on
// express: 30 comments from 3 accounts; eval held-out precision
// 69.6% → 72.7% with no recall loss. Added October 2026: a leading
// priority tag ("[P2] …", Codex-style) or a sentence starting "Automated
// review" — one match in ~39,500 human-account comments across six
// repos, and that one was an AI review.
const AI_SIGNATURE_RE =
  /(powered by|generated by)\b.{0,60}\b(GPT|GLM|Claude|Gemini|LLM|AI|model)|🤖[^\n]{0,40}\breview\b/i;
const AI_REPORT_LABEL_RE = /\*\*(Recommendation|Severity|Impact|Suggested fix|Summary|Verdict|Risk)s?:?\*\*/i;
const AI_SEVERITY_RE = /\b(severity|priority)\s*[:*]|\[(critical|high|medium|low)\]/i;
const AI_PRIORITY_TAG_RE = /^\s*(?:\*\*)?\[P[0-3]\]/;
const AI_AUTOMATED_RE = /(?:^|\n|[.!]\s+)Automated review\b/;

export function looksLikeAIReview(body = "") {
  if (AI_SIGNATURE_RE.test(body.slice(0, 200))) return "signature";
  if (AI_REPORT_LABEL_RE.test(body) && AI_SEVERITY_RE.test(body)) return "report-labels";
  if (AI_PRIORITY_TAG_RE.test(body)) return "priority-tag";
  if (AI_AUTOMATED_RE.test(body)) return "automated-review";
  return null;
}

export function isNoise(comment) {
  if (!comment?.body) return true;
  if (looksLikeAIReview(comment.body)) return true;
  if (comment.author_type && BOT_USER_TYPES.has(comment.author_type)) return true;
  if (comment.author && BOT_NAME_RE.test(comment.author)) return true;
  // Length check uses the raw body so that crisp comments like
  //   "Use `foo()` not `bar()`."
  // (which collapse to ~9 chars after stripping inline code) are not dropped
  // as "too short". Praise detection still uses the stripped form so chrome
  // (URLs, mentions) doesn't smuggle non-praise past the regex.
  if (comment.body.trim().length < 20) return true;
  if (PRAISE_RE.test(stripMarkdown(comment.body))) return true;
  return false;
}
