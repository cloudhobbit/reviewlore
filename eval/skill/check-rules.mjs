#!/usr/bin/env node
// Deterministic checks for rule files the learn-from-reviews skill writes
// (docs/plans/13-measuring-plugin-quality.md, B1). No model, no network:
// every citation is checked against a `candidates` JSON file, which is
// what the skill read.
//
//   node eval/skill/check-rules.mjs <rules-dir> <candidates.json>
//   node eval/skill/check-rules.mjs --gallery     # examples/real-repos/*/plugin
//
// Exit 1 on any failure; each line is `file: check: detail`.

import { readFileSync, readdirSync, existsSync } from "node:fs";
import { join, basename, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { globToRegExp } from "../../lib/globs.mjs";

export { globToRegExp };

const PROVENANCE = "<!-- Generated by reviewlore (learn-from-reviews)";
const NAME_RE = /^pr-feedback-[a-z0-9]+(?:-[a-z0-9]+)*\.md$/;
const CITATION_RE = /^ {2}— @([A-Za-z0-9][A-Za-z0-9-]*(?:\[bot\])?) on PR #(\d+): (https:\/\/\S+)$/;
// Globs that only cover docs, changesets or tests. A rule triggered by
// source changes must not be scoped to these (SKILL.md step 2.5).
const NON_SOURCE_RE = /(\.mdx?$|\.mdx?\}|(^|\/)docs?\/|\.changeset|(^|\/)(__)?tests?(__)?\/|\.(test|spec)\.)/;

const norm = (s) => s.replace(/\s+/g, " ").trim();

// Index every quote in a candidates file by URL.
export function indexCandidates(candidates) {
  const byUrl = new Map();
  for (const c of candidates.clusters ?? []) {
    for (const q of c.quotes ?? []) {
      const list = byUrl.get(q.url) ?? [];
      list.push(q);
      byUrl.set(q.url, list);
    }
  }
  return byUrl;
}

function parseFrontmatter(lines) {
  if (lines[0] !== "---") return { globs: [], end: 0 };
  const end = lines.indexOf("---", 1);
  if (end === -1) return { error: "frontmatter is not closed", globs: [], end: 0 };
  const body = lines.slice(1, end);
  if (body[0] !== "paths:") return { error: "frontmatter must contain only `paths:`", globs: [], end: end + 1 };
  const globs = [];
  for (const line of body.slice(1)) {
    const m = line.match(/^ {2}- "([^"]+)"$/);
    if (!m) return { error: `unexpected frontmatter line: ${line.trim()}`, globs, end: end + 1 };
    globs.push(m[1]);
  }
  if (!globs.length) return { error: "`paths:` has no globs", globs, end: end + 1 };
  return { globs, end: end + 1 };
}

function parseCitations(lines) {
  const start = lines.findIndex((l) => l.trim() === "## Examples from PR review history");
  if (start === -1) return null;
  const out = [];
  let quote = null;
  for (const line of lines.slice(start + 1)) {
    if (line.startsWith("## ")) break;
    if (line.startsWith("- > ")) quote = { text: line.slice(4), cite: null };
    else if (quote && line.startsWith("  > ")) quote.text += ` ${line.slice(4)}`;
    else if (quote && line.startsWith("  — ")) {
      const m = line.match(CITATION_RE);
      out.push({ text: quote.text, author: m?.[1], pr: m && Number(m[2]), url: m?.[3], raw: line.trim() });
      quote = null;
    }
  }
  return out;
}

// Returns [{ check, detail }] for one rule file; empty means it passes.
export function checkRule(text, fileName, quotesByUrl) {
  const fails = [];
  const fail = (check, detail) => fails.push({ check, detail });
  const lines = text.replace(/\r\n/g, "\n").split("\n");

  if (!NAME_RE.test(fileName)) fail("name", "file name must be pr-feedback-<kebab-case>.md");

  const fm = parseFrontmatter(lines);
  if (fm.error) fail("frontmatter", fm.error);
  if (!lines[fm.end]?.startsWith(PROVENANCE)) fail("provenance", "provenance comment missing right after the frontmatter");
  const anonymised = /anonymi[sz]ed/i.test(lines[fm.end] ?? "");

  const cites = parseCitations(lines);
  if (!cites) {
    fail("citations", "no `## Examples from PR review history` section");
    return fails;
  }
  if (cites.length < 2) fail("citations", `${cites.length} citation(s); need at least 2`);

  const matched = [];
  for (const c of cites) {
    if (!c.url) {
      fail("citation-format", `expected "— @author on PR #n: url", got "${c.raw}"`);
      continue;
    }
    const source = quotesByUrl.get(c.url);
    if (!source) {
      fail("citation-source", `${c.url} is not in the candidates file`);
      continue;
    }
    const hit = source.find((q) => q.author === c.author && q.pr === c.pr && norm(q.text).includes(norm(c.text)));
    if (hit) {
      matched.push(hit);
      continue;
    }
    if (!source.some((q) => q.author === c.author && q.pr === c.pr)) {
      fail("citation-source", `${c.url}: candidates has @${source[0].author} on PR #${source[0].pr}, rule says @${c.author} on PR #${c.pr}`);
    } else {
      fail("verbatim", `quote not found verbatim at ${c.url}: "${c.text.slice(0, 80)}"`);
    }
  }

  const prs = new Set(cites.filter((c) => c.pr).map((c) => c.pr));
  const authors = new Set(cites.filter((c) => c.author).map((c) => c.author.toLowerCase()));
  if (prs.size < 2) fail("evidence", `citations cover ${prs.size} PR(s); need at least 2`);
  if (authors.size < 2) fail("evidence", `citations cover ${authors.size} reviewer(s); need at least 2`);

  if (anonymised && /(^|[^\w`])@[A-Za-z0-9-]+/.test(text)) fail("anonymised", "anonymised rule still contains an @login");

  // Scope, per SKILL.md step 2.5: a rule may be scoped to where the
  // comments were made, or to the source code that triggers it when it
  // asks for tests/docs elsewhere — never only to docs/tests/changesets
  // when the comments were all on source files.
  const quotedPaths = matched.map((q) => q.path).filter(Boolean);
  const regexes = fm.globs.map((g) => [g, globToRegExp(g)]);
  // Generated rules use only **, *, ? and {a,b}; a class suggests a glob
  // the skill invented.
  for (const [glob, re] of regexes) if (!re || /[[\]]/.test(glob)) fail("scope", `invalid glob "${glob}"`);
  const valid = regexes.filter(([, re]) => re);
  if (valid.length && quotedPaths.length) {
    const sourceGlobs = valid.some(([g]) => !NON_SOURCE_RE.test(g));
    if (!sourceGlobs && quotedPaths.every((p) => !NON_SOURCE_RE.test(p))) {
      fail("scope", "scoped only to docs/changeset/test files, but the cited comments are all on source files");
    } else if (!sourceGlobs && !quotedPaths.some((p) => valid.some(([, re]) => re.test(p)))) {
      fail("scope", `globs match none of the cited comments' files (${[...new Set(quotedPaths)].join(", ")})`);
    }
  }
  return fails;
}

export function checkRulesDir(rulesDir, candidates) {
  const quotesByUrl = indexCandidates(candidates);
  const files = readdirSync(rulesDir).filter((f) => f.endsWith(".md") && f.startsWith("pr-feedback-")).sort();
  return files.map((f) => ({ file: f, fails: checkRule(readFileSync(join(rulesDir, f), "utf-8"), f, quotesByUrl) }));
}

function report(label, results) {
  let failed = 0;
  for (const { file, fails } of results) {
    for (const f of fails) {
      console.log(`${label}/${file}: ${f.check}: ${f.detail}`);
      failed++;
    }
  }
  const ok = results.filter((r) => !r.fails.length).length;
  console.error(`${label}: ${ok}/${results.length} rule files pass`);
  return failed;
}

function main(argv) {
  const here = fileURLToPath(new URL(".", import.meta.url));
  if (argv[0] === "--gallery") {
    const gallery = resolve(here, "../../examples/real-repos");
    let failed = 0;
    let checked = 0;
    for (const repo of readdirSync(gallery).sort()) {
      const rulesDir = join(gallery, repo, "plugin", ".claude", "rules");
      if (!existsSync(rulesDir)) continue;
      const snapshot = join(here, "snapshots", `${repo}.candidates.json`);
      if (!existsSync(snapshot)) {
        console.log(`${repo}: no snapshot at ${snapshot}`);
        failed++;
        continue;
      }
      const results = checkRulesDir(rulesDir, JSON.parse(readFileSync(snapshot, "utf-8")));
      checked += results.length;
      failed += report(repo, results);
    }
    if (!checked) {
      console.log("no gallery rule files found");
      return 1;
    }
    return failed ? 1 : 0;
  }
  if (argv.length !== 2) {
    console.error("Usage: check-rules.mjs <rules-dir> <candidates.json> | --gallery");
    return 1;
  }
  const [rulesDir, candidatesPath] = argv;
  const results = checkRulesDir(rulesDir, JSON.parse(readFileSync(candidatesPath, "utf-8")));
  return report(basename(resolve(rulesDir)), results) ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
